%% 1.1 История дальности (Range History)
% Cumming eq. 4.18, page 115
%
%   R(η) = sqrt(R0² + Vr²·(η - η0)²)
%
% где:
%   R(η) - мгновенная дальность до цели [м]
%   R0 - дистанция наибольшего сближения [м]
%   Vr - эффективная скорость радара [м/с]
%   η - медленное время (азимут) [с]
%   η0 - момент наибольшего сближения [с]
%
% Приближение (при малых углах):
%   R(η) ≈ R0 + (Vr²·(η - η0)²)/(2·R0)

%% 1.2 Squint angle и Doppler Centroid
% Cumming eq. 5.8, page 162
%
%   f_dc = -(2·Vr/λ)·sin(θ_squint)
%
% где:
%   f_dc - Doppler centroid [Гц]
%   θ_squint - угол визирования [рад]
%   λ - длина волны [м]
%
% Знак минус: для forward squint (радар смотрит вперёд)

%% 1.3 Doppler частота как функция азимута
% Cumming eq. 5.3, page 160
%
%   f_η(η) = -(2/λ)·dR(η)/dη
%          = -(2/λ)·(Vr²·(η - η0))/sqrt(R0² + Vr²·(η - η0)²)
%
% В момент η = η0:
%   f_η(η0) = 0  (zero Doppler)

%% ========================================================================
% РАЗДЕЛ 2: RANGE COMPRESSION
% =========================================================================

%% 2.1 Переданный LFM импульс
% Cumming eq. 4.25, page 119
%
%   s_tx(t) = rect(t/Tr)·exp(j·π·Kr·t²)
%
% где:
%   Tr - длительность импульса [с]
%   Kr - частота модуляции (chirp rate) [Гц/с]
%   rect(x) = 1 для |x| ≤ 0.5, иначе 0
%
% Полоса сигнала:
%   Br = |Kr·Tr|  [Гц]

%% 2.2 Согласованный фильтр (Range)
% Cumming eq. 6.4, page 230
%
%   H_rc(f) = exp(-j·π·f²/Kr)  для |f| ≤ Br/2
%
% Операция сжатия:
%   s_rc(t) = IFFT{ FFT{s_raw(t)} · H_rc(f) }

%% 2.3 Разрешение по дальности
% Cumming eq. 4.29, page 121
%
%   ρ_r = c/(2·Br)  [м]
%
% Типичные значения:
%   Br = 50 МГц  →  ρ_r = 3 м
%   Br = 100 МГц →  ρ_r = 1.5 м

%% ========================================================================
% РАЗДЕЛ 3: AZIMUTH FFT И RANGE-DOPPLER DOMAIN
% =========================================================================

%% 3.1 Переход в Range-Doppler domain
% Cumming Section 6.3.2, page 231
%
%   S_rd(t, f_η) = FFT_η{ S_rc(t, η) }
%
% где:
%   t - быстрое время (range)
%   f_η - Doppler частота (azimuth frequency)

%% 3.2 Ось Doppler частот
%
%   f_η = ((0:N-1) - N/2)·(PRF/N) + f_dc
%
% где:
%   N - число импульсов
%   PRF - частота повторения импульсов [Гц]
%   f_dc - Doppler centroid [Гц]
%
% Диапазон:
%   f_η ∈ [f_dc - PRF/2, f_dc + PRF/2]

%% 3.3 Azimuth bandwidth
% Cumming eq. 4.61, page 131
%
%   Bd_az = 2·Vr/La  [Гц]
%
% где:
%   La - физическая длина антенны [м]
%
% Связь с разрешением по азимуту:
%   ρ_a = La/2  [м]  (для stripmap SAR)

%% ========================================================================
% РАЗДЕЛ 4: RANGE CELL MIGRATION
% =========================================================================

%% 4.1 D функция (ключевая для RCMC)
% Cumming eq. 6.11, page 233
%
%   D(f_η) = sqrt(1 - (λ·f_η/(2·Vr))²)
%
% Свойства:
%   - При f_η = 0 (zero Doppler):  D = 1
%   - При f_η = ±2·Vr/λ:  D = 0 (критическая частота)
%   - Обычно D ≈ 0.999...1

%% 4.2 Range migration в Range-Doppler domain
% Cumming eq. 6.10-6.12, page 233-234
%
%   ΔR(f_η, R0) = R0·[D(f_η) - 1]
%
% Для малых углов (приближение):
%   ΔR(f_η, R0) ≈ -R0·(λ·f_η/(2·Vr))²/2
%
% Максимальная миграция (при f_η = Bd_az/2):
%   ΔR_max ≈ R0·(λ·Bd_az/(4·Vr))²

%% 4.3 Пример расчёта миграции
%
% Дано:
%   R0 = 20 км
%   λ = 0.0566 м
%   Vr = 150 м/с
%   Bd_az = 80 Гц
%
% D(Bd_az/2) = sqrt(1 - (0.0566 × 40 / 300)²)
%            = sqrt(1 - 0.0000566)
%            ≈ 0.999972
%
% ΔR_max = 20000 × (0.999972 - 1)
%        ≈ -0.56 м
%
% При ρ_r = 2.5 м → миграция через 0.22 range bins

%% ========================================================================
% РАЗДЕЛ 5: RCMC (RANGE CELL MIGRATION CORRECTION)
% =========================================================================

%% 5.1 RCMC операция
% Cumming Section 6.3.3, page 233-235
%
% Для каждой Doppler частоты f_η:
%
%   1. Вычислить D(f_η) = sqrt(1 - (λ·f_η/(2·Vr))²)
%
%   2. Найти миграцию: ΔR(f_η) = R0_ref·[D(f_η) - 1]
%
%   3. Перевести в time shift: Δt(f_η) = 2·ΔR(f_η)/c
%
%   4. Интерполировать:
%      S_rcmc(t, f_η) = interpolate{ S_rd(t + Δt(f_η), f_η) }
%
% Где R0_ref - референсная дальность (обычно центр сцены)

%% 5.2 Остаточная миграция
% Для цели на дистанции R ≠ R0_ref:
%
%   ΔR_residual(f_η) = (R - R0_ref)·[D(f_η) - 1]
%
% Если |R - R0_ref| велика → нужен SRC

%% ========================================================================
% РАЗДЕЛ 6: AZIMUTH COMPRESSION
% =========================================================================

%% 6.1 Azimuth matched filter
% Cumming eq. 6.15-6.16, page 236-237
%
%   H_ac(f_η, R0) = exp(j·4π·R0·D(f_η)/λ)
%
% Физический смысл:
%   Компенсирует фазовые изменения вдоль гиперболы R(η)

%% 6.2 Операция азимутальной компрессии
%
%   S_ac(t, f_η) = S_rcmc(t, f_η)·H_ac(f_η)
%   S_focused(t, η) = IFFT_η{ S_ac(t, f_η) }

%% 6.3 Фазовая история цели (до компрессии)
% Cumming eq. 6.2, page 227
%
%   Φ(η) = -4π·R(η)/λ
%        = -4π·sqrt(R0² + Vr²·(η - η0)²)/λ
%
% Приближение:
%   Φ(η) ≈ -4π·R0/λ - 2π·Vr²·(η - η0)²/(λ·R0)
%
% Второй член = квадратичная фаза → azimuth chirp

%% ========================================================================
% РАЗДЕЛ 7: SECONDARY RANGE COMPRESSION (SRC)
% =========================================================================

%% 7.1 Причина необходимости SRC
% После RCMC остаётся coupling между range и azimuth:
%
%   Φ_residual(f_r, f_η) ≈ π·f_r²·Km(f_η)
%
% где f_r - range frequency

%% 7.2 SRC modulation rate (Option 2)
% Cumming eq. 6.30, page 248
%
%   Km(f_η) = -λ²·R0/(8·Vr²·D(f_η)³)
%
% Свойства:
%   - Km зависит от f_η → разный для каждой Doppler частоты
%   - Km < 0 (отрицательный chirp)
%   - |Km| << |Kr| (малая модуляция)

%% 7.3 SRC фильтр (Accurate - Option 2)
% Cumming eq. 6.31-6.32, page 248-250
%
%   H_SRC(f_r, f_η) = exp(j·π·f_r²/Km(f_η))
%
% Применение:
%   1. Range FFT: S(f_r, f_η) = FFT_t{ S_rcmc(t, f_η) }
%   2. Умножение: S_src(f_r, f_η) = S(f_r, f_η)·H_SRC(f_r, f_η)
%   3. Range IFFT: S_src(t, f_η) = IFFT_f_r{ S_src(f_r, f_η) }

%% 7.4 SRC фильтр (Approximate - Option 3)
% Cumming eq. 6.33, page 251
%
%   H_SRC_approx(f_r) = exp(j·π·f_r²/Km(f_dc))
%
% где используется ОДНО значение Km для центрального Doppler f_dc
%
% Применение ПОСЛЕ azimuth compression
%
% Ограничения:
%   - Работает только при малой Bd_az
%   - Ошибка растёт при большом squint

%% 7.5 Пример расчёта Km
%
% Дано:
%   R0 = 20 км
%   λ = 0.0566 м
%   Vr = 150 м/с
%   f_η = 0 (zero Doppler)
%
% D(0) = 1
% Km(0) = -0.0566² × 20000 / (8 × 150² × 1³)
%       = -64.0656 / 180000
%       ≈ -3.56e-4 Гц⁻¹
%
% Для сравнения:
%   Kr = 20e12 Гц⁻¹
%   |Km/Kr| ≈ 1.78e-17 (очень малое!)

%% ========================================================================
% РАЗДЕЛ 8: ИМПУЛЬСНАЯ ХАРАКТЕРИСТИКА
