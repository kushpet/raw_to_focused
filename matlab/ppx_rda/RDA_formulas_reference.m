%% 8.1 Разрешение по дальности (Range Resolution)
% Cumming eq. 4.29, page 121
%
%   ρ_r = c/(2·Br)  [м]
%
% 3 дБ ширина (половинная мощность):
%   Δr_3dB ≈ 0.886·ρ_r

%% 8.2 Разрешение по азимуту (Azimuth Resolution)
% Cumming eq. 4.61, page 131
%
% Для stripmap SAR:
%   ρ_a = La/2  [м]
%
% где La - длина антенны
%
% 3 дБ ширина:
%   Δa_3dB ≈ 0.886·ρ_a

%% 8.3 Peak Sidelobe Ratio (PSLR)
% Для идеального LFM сигнала:
%
%   PSLR = -13.3 дБ  (без взвешивания)
%
% С окном Hamming:
%   PSLR ≈ -43 дБ
%
% С окном Taylor:
%   PSLR ≈ -35 дБ (регулируется)

%% 8.4 Integrated Sidelobe Ratio (ISLR)
% Для идеального LFM:
%
%   ISLR = -10 дБ  (без взвешивания)

