%% 9.1 Связь между time и frequency domain
%
% FFT:  F(ω) = ∫ f(t)·exp(-j·ω·t) dt
% IFFT: f(t) = (1/2π)·∫ F(ω)·exp(j·ω·t) dω

%% 9.2 Свойство сдвига (для RCMC)
%
%   Если f(t) <=> F(ω)
%   то  f(t - t0) <=> F(ω)·exp(-j·ω·t0)
%
% Поэтому сдвиг во времени = интерполяция

%% 9.3 Свёртка как умножение
%
%   Matched filter:
%   y(t) = s(t) * h(t)  <==>  Y(f) = S(f)·H(f)
%
% где * обозначает свёртку

