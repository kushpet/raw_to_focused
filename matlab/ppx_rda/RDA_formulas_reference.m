%% 12.1 Когда Basic RDA достаточно?
%
% Условие: Остаточная миграция после RCMC мала
%
%   ΔR_residual < ρ_r/4
%
% Типично для:
%   - Малый squint (< 5°)
%   - Узкий swath (ΔR_scene < 10% R0)
%   - Средняя разрешение (ρ_r > 1 м)

%% 12.2 Когда нужен SRC?
%
% Условие: Остаточная фазовая ошибка значительна
%
%   |Φ_residual| > π/4
%
% Типично для:
%   - Большой squint (> 10°)
%   - Широкий swath (ΔR_scene > 20% R0)
%   - Высокое разрешение (ρ_r < 1 м)

%% 12.3 Option 2 vs Option 3 SRC?
%
% Option 2 (Accurate, перед Az compression):
%   - Всегда предпочтительнее
%   - Точная коррекция для всех f_η
%   - Чуть больше вычислений
%
% Option 3 (Approximate, после Az compression):
%   - Проще реализовать
%   - Работает только при Bd_az/f_dc < 0.1
%   - Может использоваться для broadside (θ_squint ≈ 0)

