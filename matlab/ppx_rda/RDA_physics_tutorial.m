%% 2.1 BASIC RDA (Cumming Fig 6.1a) - 4 шага

% ШАГ 1: RANGE COMPRESSION
%   Вход: Raw data S_raw(t, η)
%   Операция: Matched filter по fast time t
%   
%   Формула (Cumming eq. 6.4):
%       S_rc(t, η) = IFFT{ FFT{S_raw} · H_rc^*(f) }
%   
%   где H_rc(f) = exp(j·π·f²/Kr) - сопряжённый LFM chirp
%   
%   Результат: Сжатие по дальности, разрешение ρ_r = c/(2·Br)

% ШАГ 2: AZIMUTH FFT
%   Вход: S_rc(t, η)
%   Операция: FFT по медленному времени η
%   
%   Формула:
%       S_rd(t, f_η) = FFT_η{ S_rc(t, η) }
%   
%   Результат: Переход в Range-Doppler domain
%   - Горизонталь: Doppler frequency
%   - Вертикаль: Range time

% ШАГ 3: RCMC
%   Вход: S_rd(t, f_η)
%   Операция: Интерполяция для каждой f_η
%   
%   Для каждой Doppler частоты f_η:
%       1. Вычислить D(f_η) = sqrt(1 - (λ·f_η/(2·V))²)
%       2. Найти миграцию: ΔR = R0_ref·[D(f_η) - 1]
%       3. Сдвиг по времени: Δt = 2·ΔR/c
%       4. Интерполяция: S_rcmc(t, f_η) = S_rd(t + Δt, f_η)
%   
%   Результат: Энергия цели выровнена по range

% ШАГ 4: AZIMUTH COMPRESSION
%   Вход: S_rcmc(t, f_η)
%   Операция: Matched filter по Doppler
%   
%   Формула (Cumming eq. 6.15):
%       H_ac(f_η) = exp(j·4π·R0_ref·D(f_η)/λ)
%       S_ac(t, f_η) = S_rcmc(t, f_η) · H_ac(f_η)
%       S_focused(t, η) = IFFT_η{ S_ac }
%   
%   Результат: Сфокусированное изображение

%% 2.2 RDA with ACCURATE SRC (Cumming Fig 6.1b) - 5 шагов

% ШАГ 1-3: Как в Basic RDA
%   Range compression → Az FFT → RCMC

% ШАГ 3.5: SRC (Option 2) - ПЕРЕД azimuth compression
%   Вход: S_rcmc(t, f_η)
%   Операция: Коррекция остаточной phase modulation
%   
%   Процедура:
%       1. Range FFT: S_rd_2D(f_r, f_η) = FFT_t{ S_rcmc }
%       2. Для каждой f_η вычислить:
%           Km(f_η) = -λ²·R0/(8·V²·D(f_η)³)
%       3. Применить SRC фильтр:
%           H_SRC(f_r, f_η) = exp(j·π·f_r²/Km(f_η))
%           S_src(f_r, f_η) = S_rd_2D(f_r, f_η) · H_SRC(f_r, f_η)
%       4. Range IFFT: S_src(t, f_η) = IFFT_f_r{ S_src }
%   
%   Результат: Точная коррекция для всех дистанций

% ШАГ 4: Azimuth compression - как в Basic RDA

%% 2.3 RDA with APPROXIMATE SRC (Cumming Fig 6.1c) - 5 шагов

% ШАГ 1-4: Как в Basic RDA (полная обработка без SRC)

% ШАГ 5: SRC (Option 3) - ПОСЛЕ azimuth compression
%   Вход: S_focused(t, η) - уже сфокусированное изображение
%   Операция: Приближённая коррекция
%   
%   Процедура:
%       1. Использовать ЦЕНТРАЛЬНЫЙ Doppler f_dc
%       2. Вычислить Km для f_dc:
%           Km_approx = -λ²·R0/(8·V²·D(f_dc)³)
%       3. Применить ОДИН SRC фильтр для всех азимутов:
%           Range FFT → multiply by H_SRC → Range IFFT
%   
%   Результат: Приближённая коррекция
%   Ограничение: Работает только при малой Doppler bandwidth

