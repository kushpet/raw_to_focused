%% Sentinel-1 использует модифицированный RDA:
%
% 1. Preprocessing:
%    - Doppler centroid estimation
%    - Timing calibration
%
% 2. Range Compression:
%    - Replica correlation (как в RDA)
%    - Range filtering
%
% 3. Azimuth Processing:
%    - Extended Chirp Scaling (ECS) - более продвинутая версия RCMC
%    - Range cell migration correction
%    - Azimuth compression
%
% 4. Postprocessing:
%    - Interferometric corrections
%    - Radiometric calibration
%
% ОСНОВНОЕ ОТЛИЧИЕ от классического RDA:
%   - ECS allows более точную RCMC для больших swath
%   - Учёт Earth rotation
%   - Учёт orbit variations

