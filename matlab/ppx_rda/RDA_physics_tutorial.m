%% 1.1 DOPPLER CENTROID (f_dc) - Что это и почему важно?
%
% ОПРЕДЕЛЕНИЕ:
%   Doppler Centroid - это центральная частота доплеровского спектра
%   отражённого сигнала. Для stripmap SAR это константа.
%
% ФИЗИЧЕСКАЯ ПРИЧИНА:
%   Когда радар "смотрит" не перпендикулярно траектории (squint ≠ 0),
%   между радаром и целью есть постоянная радиальная скорость:
%
%       V_radial = V_platform · sin(θ_squint)
%
%   где θ_squint - угол визирования относительно перпендикуляра
%
% ФОРМУЛА (Cumming eq. 5.8, page 162):
%
%       f_dc = -(2 / λ) · V_radial = -(2·V / λ) · sin(θ_squint)
%
%   где:
%       λ - длина волны
%       V - скорость платформы
%
% ПРИМЕР РАСЧЁТА:
%   V = 150 м/с
%   λ = 0.0566 м (f0 = 5.3 GHz)
%   θ_squint = 3.5°
%
%   f_dc = -(2 × 150 / 0.0566) × sin(3.5°)
%        = -5300 × 0.061
%        ≈ -323 Hz
%
%   (Близко к значению 320 Hz из Table 6.1)
%
% ВЛИЯНИЕ SQUINT ANGLE:
%   - Малый squint (< 5°): f_dc ~ несколько сотен Hz
%   - Большой squint (> 20°): f_dc ~ тысячи Hz
%   - Zero squint (broadside): f_dc = 0 Hz
%
% ВАЖНОСТЬ ДЛЯ ОБРАБОТКИ:
%   1. Если не скомпенсировать f_dc → азимутальная расфокусировка
%   2. f_dc влияет на позицию спектра в азимутальной частотной области
%   3. RCMC зависит от f_dc (разная миграция для разных Doppler частот)

%% 1.2 FFT ПО АЗИМУТУ - Переход в Range-Doppler координаты
%
% ВОПРОС: Зачем делать FFT по азимуту?
%
% ОТВЕТ: Эффективность обработки и физический смысл
%
% ФИЗИЧЕСКИЙ СМЫСЛ:
%   Каждая точка в азимутальной частотной области соответствует
%   определённой геометрии радар-цель:
%
%       f_η ↔ определённый момент пролёта радара
%       f_η ↔ определённая радиальная скорость
%       f_η ↔ точки на гиперболической траектории
%
% КЛЮЧЕВОЕ СВОЙСТВО (Cumming, page 226):
%   "Targets at the SAME RANGE but DIFFERENT AZIMUTH positions 
%    have energy at DIFFERENT Doppler frequencies"
%
%   Пример:
%       Цель A: R0 = 20 км, Az = 100 м  →  f_η_A
%       Цель B: R0 = 20 км, Az = 200 м  →  f_η_B ≠ f_η_A
%
%   НО! После FFT по азимуту:
%       - Обе цели на одной дистанции R0
%       - Но на разных Doppler частотах
%
% ПРЕИМУЩЕСТВА:
%   1. RCMC для одной Doppler частоты корректирует ВСЕ цели на этой частоте
%   2. Matched filter в частотной области = простое умножение
%   3. Блочная обработка эффективнее
%
% НАЗВАНИЕ "Range-Doppler domain":
%   - Горизонталь: Doppler frequency (азимут в частотной области)
%   - Вертикаль: Range time (дальность во временной области)

%% 1.3 RANGE CELL MIGRATION (RCM) - Что это?
%
% ПРОБЛЕМА:
%   Цель движется по гиперболической траектории относительно радара:
%
%       R(η) = sqrt(R0² + (V·η)²)
%
%   где:
%       η - медленное время (азимут)
%       R0 - дистанция наибольшего сближения
%
% СЛЕДСТВИЕ:
%   Сигнал от цели "мигрирует" через несколько range bins:
%
%       η = -T/2  →  R = R0 + ΔR  →  Range bin N+k
%       η = 0     →  R = R0       →  Range bin N
%       η = +T/2  →  R = R0 + ΔR  →  Range bin N+k
%
%   где ΔR - максимальная миграция
%
% ВЕЛИЧИНА МИГРАЦИИ (Cumming eq. 6.10, page 233):
%
%       ΔR_max ≈ (V² · T_synth²) / (8 · R0)
%
%   Для типичных параметров:
%       V = 150 м/с
%       T_synth = 1 с (время синтеза)
%       R0 = 20 км
%
%       ΔR_max ≈ (150² × 1²) / (8 × 20000) ≈ 0.14 м
%
%   При разрешении по дальности ρ_r = 2.5 м:
%       Миграция через ~0.06 range bins (малая)
%
%   НО! При высоком разрешении (ρ_r = 0.5 м):
%       Миграция через ~0.28 range bins (заметная)
%
% ФОРМУЛА МИГРАЦИИ В RANGE-DOPPLER DOMAIN (Cumming eq. 6.11):
%
%       ΔR(f_η) = R0 · [sqrt(1 - (λ·f_η/(2·V))²) - 1]
%                 \_____________________________/
%                              D(f_η)
%
%   Ключевое наблюдение:
%       - Разные Doppler частоты → разная миграция
%       - Но для фиксированного R0 → одинаковая форма траектории

%% 1.4 RANGE CELL MIGRATION CORRECTION (RCMC)
%
% ЦЕЛЬ:
%   Выровнять все отсчёты от одной цели в один range bin
%
% МЕТОД В RDA:
%   Коррекция в Range-Doppler domain путём интерполяции
%
% ПРОЦЕДУРА (Cumming, page 233-234):
%   1. Для каждой Doppler частоты f_η:
%       a) Вычислить миграцию: ΔR(f_η) = R0·[D(f_η) - 1]
%       b) Перевести в сдвиг по времени: Δt = 2·ΔR/c
%       c) Интерполировать данные: сдвинуть на -Δt
%
%   2. После RCMC: все отсчёты от цели выровнены по range
%
% ЭФФЕКТИВНОСТЬ:
%   Одна операция интерполяции для каждой f_η корректирует
%   ВСЕ цели на дистанции R0 → блочная эффективность!
%
% ВАЖНОЕ ЗАМЕЧАНИЕ:
%   RCMC использует РЕФЕРЕНСНУЮ дистанцию R0_ref
%   - Для целей с R ≈ R0_ref → точная коррекция
%   - Для целей с R ≠ R0_ref → остаточная миграция
%   → Решение: Secondary Range Compression (SRC)

%% 1.5 SECONDARY RANGE COMPRESSION (SRC)
%
% ПРОБЛЕМА:
%   После RCMC остаётся ОСТАТОЧНАЯ фазовая модуляция по дальности
%
% ФИЗИЧЕСКАЯ ПРИЧИНА:
%   RCMC идеально работает только для R = R0_ref
%   Для других дистанций:
%       - Trajectory shape немного отличается
%       - Остаётся coupling между range и azimuth
%
% МАТЕМАТИКА (Cumming eq. 6.29, page 248):
%   Остаточная фазовая модуляция имеет квадратичную форму:
%
%       Φ_residual(f_r, f_η) ≈ π · f_r² · Km(f_η)
%
%   где Km(f_η) - модуляционная частота, зависящая от Doppler
%
% КОМПЕНСАЦИЯ - SRC ФИЛЬТР:
%
%       H_SRC(f_r, f_η) = exp(-j·π·f_r²·Km(f_η))
%
%   где:
%       Km(f_η) = -λ²·R0 / (8·Vr²·D(f_η)³)
%
% ДВА ВАРИАНТА (Cumming Fig 6.1):
%
%   Option 2 (Fig 6.1b): SRC ПЕРЕД azimuth compression
%       - Точная коррекция
%       - SRC зависит от f_η → применяется в Range-Doppler domain
%       - Требует Range FFT, применение фильтра, Range IFFT
%
%   Option 3 (Fig 6.1c): SRC ПОСЛЕ azimuth compression
%       - Приближённая коррекция
%       - Использует ОДИН фильтр для центрального Doppler f_dc
%       - Проще, но менее точно
%       - Работает при малой азимутальной полосе

