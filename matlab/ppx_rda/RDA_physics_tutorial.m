%% 3.1 Выбор референсной дистанции R0_ref
%
% ВАЖНОСТЬ:
%   R0_ref определяет качество RCMC и SRC
%
% РЕКОМЕНДАЦИИ:
%   - Для одной цели: R0_ref = R_target
%   - Для сцены: R0_ref = R_scene_center
%   - Для swath: может потребоваться разбиение на patches

%% 3.2 Интерполация в RCMC
%
% МЕТОДЫ:
%   - Linear: быстро, но менее точно
%   - Cubic: точнее, медленнее
%   - Sinc: теоретически оптимально, очень медленно
%
% ВЫБОР:
%   Linear достаточно для большинства случаев

%% 3.3 Влияние параметров на качество
%
% BANDWIDTH:
%   Больше Br → лучше range resolution
%   Больше Bd_az → лучше azimuth resolution
%
% SQUINT ANGLE:
%   Малый squint (< 5°): Basic RDA может быть достаточно
%   Большой squint (> 20°): Нужен SRC
%
% SCENE SIZE:
%   Большая сцена → может понадобиться разбиение на patches
%   с разными R0_ref для каждого patch

